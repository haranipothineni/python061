####### Swapping Two Variables

### Method 1: Using a temporary variable
# a = 10
# b = 20
# temp = a
# a = b
# b = temp
# print(a, b)

### Method 2: Without Using a Third Variable (Arithmetic Method)
# a = 10
# b = 20
# a = a + b
# b = a - b
# a = a - b
# print(a, b)

### Method 3: Pythonic Swapping 
# a = 10
# b = 20
# a, b = b, a
# print(a, b)

